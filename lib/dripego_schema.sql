-- ==========================================
-- 1. ROLES & AUTH ENTITIES
-- ==========================================

CREATE TYPE public.user_role AS ENUM ('super_admin', 'admin', 'customer');

CREATE TABLE IF NOT EXISTS public.user_roles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role public.user_role DEFAULT 'customer'::public.user_role NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Trigger to automatically assign 'super_admin' to the first user, and 'customer' to others
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER SECURITY DEFINER AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.user_roles WHERE role IN ('admin', 'super_admin')) THEN
        INSERT INTO public.user_roles (id, role)
        VALUES (NEW.id, 'super_admin');
    ELSE
        INSERT INTO public.user_roles (id, role)
        VALUES (NEW.id, 'customer');
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Enable RLS
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;

