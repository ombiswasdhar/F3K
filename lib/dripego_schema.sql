-- ==========================================
-- 10. ROW LEVEL SECURITY (RLS) POLICIES
-- ==========================================

-- Helper function to check if user has admin/super_admin privileges
CREATE OR REPLACE FUNCTION public.is_admin(user_id UUID)
RETURNS BOOLEAN SECURITY DEFINER AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.user_roles 
        WHERE id = user_id AND role IN ('admin', 'super_admin')
    );
END;
$$ LANGUAGE plpgsql;

-- User Roles Policies
CREATE POLICY "Admins can view all roles" ON public.user_roles
    FOR SELECT USING (public.is_admin(auth.uid()));
CREATE POLICY "Admins can update user roles" ON public.user_roles
    FOR ALL USING (auth.uid() = id OR public.is_admin(auth.uid()));

-- Products Policies
CREATE POLICY "Anyone can view published products" ON public.products
    FOR SELECT USING (status = 'published'::public.product_status OR public.is_admin(auth.uid()));
CREATE POLICY "Admins can perform all modifications on products" ON public.products
    FOR ALL USING (public.is_admin(auth.uid()));

-- Categories Policies
CREATE POLICY "Anyone can view categories" ON public.categories
    FOR SELECT USING (true);
CREATE POLICY "Admins can perform all modifications on categories" ON public.categories
    FOR ALL USING (public.is_admin(auth.uid()));

-- Orders Policies
CREATE POLICY "Users can view their own orders" ON public.orders
    FOR SELECT USING (auth.uid() = customer_id OR public.is_admin(auth.uid()));
CREATE POLICY "Anyone can insert an order" ON public.orders
    FOR INSERT WITH CHECK (true);
CREATE POLICY "Admins can edit/view all orders" ON public.orders
    FOR ALL USING (public.is_admin(auth.uid()));

-- Order Items Policies
CREATE POLICY "Users can view their own order items" ON public.order_items
    FOR SELECT USING (
        EXISTS (
            SELECT 1 FROM public.orders 
            WHERE id = order_id AND (customer_id = auth.uid() OR public.is_admin(auth.uid()))
        )
    );
CREATE POLICY "Anyone can insert order items" ON public.order_items
    FOR INSERT WITH CHECK (true);
CREATE POLICY "Admins can modify all order items" ON public.order_items
    FOR ALL USING (
        EXISTS (
            SELECT 1 FROM public.orders 
            WHERE id = order_id AND public.is_admin(auth.uid())
        )
    );

-- Waitlist Policies
CREATE POLICY "Anyone can sign up to waitlist" ON public.waitlist
    FOR INSERT WITH CHECK (true);
CREATE POLICY "Admins can view and edit waitlist" ON public.waitlist
    FOR ALL USING (public.is_admin(auth.uid()));

-- Inventory Logs Policies
CREATE POLICY "Admins can manage inventory logs" ON public.inventory_logs
    FOR ALL USING (public.is_admin(auth.uid()));

-- Content Settings Policies
CREATE POLICY "Anyone can view content settings" ON public.content_settings
    FOR SELECT USING (true);
CREATE POLICY "Admins can modify content settings" ON public.content_settings
    FOR ALL USING (public.is_admin(auth.uid()));

-- Media Library Policies
CREATE POLICY "Admins can manage media" ON public.media_library
    FOR ALL USING (public.is_admin(auth.uid()));

-- Activity Logs Policies
CREATE POLICY "Admins can view activity logs" ON public.activity_logs
    FOR ALL USING (public.is_admin(auth.uid()));


